function getLevelInstructions(targetLang: string, nativeLang: string, level: string): string {
  switch (level) {
    case 'zero':
      return `LEVEL: COMPLETE ZERO — The student knows NO words in ${targetLang}. This is their very first exposure.

LANGUAGE MIX: Speak about 70% in ${nativeLang} and 30% in ${targetLang}.
- Introduce ONE new word or very short phrase per turn.
- Always say the new word in ${targetLang}, then immediately explain it in ${nativeLang}.
- Ask the student to repeat the word back to you.
- Use simple, encouraging ${nativeLang} to keep them comfortable.
- Build vocabulary slowly: greetings first, then thank you, yes, no, please, numbers 1-5.
- Celebrate every attempt, even if pronunciation is rough.
- If the student tries to say something in ${targetLang}, praise them enthusiastically.
- Keep the mood light and fun — this should feel like a game, not a class.`

    case 'beginner':
      return `LEVEL: BEGINNER — The student knows basic words (hello, thank you, numbers, simple phrases).

LANGUAGE MIX: Speak about 50% in ${targetLang} and 50% in ${nativeLang}.
- Use simple, short sentences in ${targetLang} (3-6 words).
- After each ${targetLang} sentence, give a brief ${nativeLang} explanation if it contains new vocabulary.
- When the student speaks in ${nativeLang}, gently suggest how to say it in ${targetLang} and ask them to try.
- Introduce 2-3 new words per conversation, repeating them naturally.
- If the student doesn't understand after one try, switch fully to ${nativeLang} to explain, then try ${targetLang} again.
- Ask simple questions they can answer with words they know.`

    case 'advanced':
      return `LEVEL: ADVANCED — The student wants fluent practice and detailed corrections.

LANGUAGE MIX: Speak 95-100% in ${targetLang}. Only use ${nativeLang} if explicitly asked.
- Speak naturally as a native speaker would — normal speed, natural expressions, idioms.
- Use varied vocabulary and complex sentence structures.
- Correct grammar mistakes specifically: say what they said, then the correct version, then briefly explain why (all in ${targetLang}).
- Challenge them with questions that require longer, more complex answers.
- Introduce idioms, slang, and cultural expressions naturally.
- If they make the same mistake twice, point it out directly but kindly.
- Discuss deeper topics: opinions, hypotheticals, cultural differences, current events.
- Push them to express nuance.`

    default: // intermediate
      return `LEVEL: INTERMEDIATE — The student can hold a simple conversation.

LANGUAGE MIX: Speak about 80% in ${targetLang} and 20% in ${nativeLang}.
- Speak primarily in ${targetLang}. The student needs immersion.
- When the student seems confused or asks for help, briefly explain in ${nativeLang}.
- Match the student's complexity. Simple words from them → simple responses. Complex grammar → you can be more advanced.
- If the student speaks in ${nativeLang}, respond in ${targetLang} but at a simpler level.
- If the student speaks ${nativeLang} for 2+ turns in a row, gently ask if they'd like to try in ${targetLang}, then give them a simple sentence to start with.
- Correct mistakes by naturally repeating what they said correctly, then continue.`
  }
}

function buildSystemPrompt(languageCode: string, level: string, nativeLang: string): string {
  const lang = LANGUAGE_CONFIG[languageCode]
  if (!lang) throw new Error(`Unsupported language: ${languageCode}`)

  const nativeLangName = LANGUAGE_CONFIG[nativeLang]?.name || NATIVE_LANGUAGE_NAMES[nativeLang] || 'English'
  const levelInstructions = getLevelInstructions(lang.name, nativeLangName, level)

  return `You are a friendly, patient language tutor helping someone practice ${lang.name} (${lang.nativeName}).
The student's native language is ${nativeLangName}.

${levelInstructions}

GENERAL RULES:
- Keep responses SHORT: 1-3 sentences maximum. This is spoken conversation, not a lecture.
- Correct mistakes naturally: repeat what they said correctly, then continue. Do NOT lecture about grammar rules unless asked.
- NEVER use parenthetical stage directions like (slowly), (whispering), (laughing). Your text will be read aloud by a speech engine — it cannot act, only speak.
- NEVER use "..." for dramatic pauses or to slow down speech. The speech engine reads dots literally. Use short sentences with natural punctuation.
- Ask ONE question per response to keep the conversation flowing.
- Stay on conversational topics: daily life, hobbies, food, travel, culture, weather, family.
- If asked about unrelated topics (politics, math, coding, etc.), redirect warmly back to practicing ${lang.name}.
- Never break character. You are a language tutor, not a general AI assistant.
- Use natural conversational fillers in ${lang.name}: ${lang.fillers}

PERSONALITY: Warm, encouraging, patient. Curious about the student's life to generate natural topics. Like a friend who happens to be a native speaker.`
}

/**
 * Clean LLM output for TTS consumption.
 * Removes stage directions, pacing dots, and other artifacts
 * that TTS engines would read literally.
 */
function sanitizeForTTS(text: string): string {
  return text
    // Remove parenthetical stage directions: (slowly), (laughing), (whispering), etc.
    .replace(/\([\w\s]+\)/gi, '')
    // Remove bracketed stage directions: [slowly], [pause], etc.
    .replace(/\[[\w\s]+\]/gi, '')
    // Remove pacing ellipsis: "I... am..." → "I am"
    .replace(/\.{2,}/g, ' ')
    // Remove asterisk emphasis: *slowly*, **pause**, etc.
    .replace(/\*+[\w\s]+\*+/g, '')
    // Collapse multiple spaces left by removals
    .replace(/\s{2,}/g, ' ')
    .trim()
}

async function generateSpeech(
  text: string,
  language: string,
  mistralKey: string,
  voiceId?: string,
  elevenLabsVoiceId?: string,
): Promise<Buffer> {
  if (VOXTRAL_SUPPORTED.has(language)) {
    const voiceConfig = VOICE_MAP[language]
    const ttsBody: Record<string, unknown> = {
      model: 'voxtral-mini-tts-2603',
      input: text,
      response_format: 'mp3',
    }
    const resolvedVoiceId = voiceId || (voiceConfig?.voiceId !== 'xxx' ? voiceConfig?.voiceId : undefined)
    if (resolvedVoiceId) {
      ttsBody.voice_id = resolvedVoiceId
    } else {
      ttsBody.voice = language === 'ar' ? 'en_paul_confident' : 'en_paul_cheerful'
    }
    let ttsResponse: Response | null = null
    for (let attempt = 0; attempt < 2; attempt++) {
      ttsResponse = await fetchWithTimeout('https://api.mistral.ai/v1/audio/speech', {
        method: 'POST',
        headers: {
          Authorization: `Bearer ${mistralKey}`,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify(ttsBody),
      }, 20000, 'Mistral TTS')
      if (ttsResponse.ok) break
      if (attempt === 0) {
        console.warn(`Mistral TTS attempt 1 failed with ${ttsResponse.status}, retrying...`)
        await new Promise(r => setTimeout(r, 500))
      }
    }
    if (!ttsResponse || !ttsResponse.ok) {
      throw new Error(`Mistral TTS failed: ${ttsResponse?.status ?? 'unknown'}`)
    }
    const ttsJson = await ttsResponse.json() as { audio_data?: string }
    if (!ttsJson.audio_data) throw new Error('Mistral TTS returned no audio_data field')
    return Buffer.from(ttsJson.audio_data, 'base64')
  } else {
    const elevenKey = process.env.ELEVENLABS_API_KEY
    if (!elevenKey) throw new Error('ELEVENLABS_API_KEY not configured')
    const resolvedElVoiceId = elevenLabsVoiceId || ELEVENLABS_FALLBACK[language]
    if (!resolvedElVoiceId) throw new Error(`No TTS voice configured for language: ${language}`)
    const voiceId = resolvedElVoiceId
    const response = await fetchWithTimeout(`https://api.elevenlabs.io/v1/text-to-speech/${voiceId}`, {
      method: 'POST',
      headers: { 'xi-api-key': elevenKey, 'Content-Type': 'application/json' },
      body: JSON.stringify({
        text,
        model_id: 'eleven_multilingual_v2',
        voice_settings: { stability: 0.5, similarity_boost: 0.75 },
      }),
    }, 20000, 'ElevenLabs TTS')
    if (!response.ok) throw new Error(`ElevenLabs TTS failed: ${response.status}`)
    return Buffer.from(await response.arrayBuffer())
  }
}

function fetchWithTimeout(url: string, options: RequestInit, timeoutMs: number, label: string): Promise<Response> {
  const controller = new AbortController()
  const timer = setTimeout(() => controller.abort(), timeoutMs)
  console.log(`[voice-chat] ${label} — starting (${timeoutMs}ms timeout)`)
  return fetch(url, { ...options, signal: controller.signal })
    .then((res) => {
      clearTimeout(timer)
      console.log(`[voice-chat] ${label} — completed (status ${res.status})`)
      return res
    })
    .catch((err) => {
      clearTimeout(timer)
      if (err.name === 'AbortError') {
        console.error(`[voice-chat] ${label} — TIMED OUT after ${timeoutMs}ms`)
        throw new Error(`${label} timed out after ${timeoutMs / 1000}s`)
      }
      console.error(`[voice-chat] ${label} — FAILED:`, err.message)
      throw err
    })
}

const CORS_HEADERS = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Methods': 'POST, OPTIONS',
  'Access-Control-Allow-Headers': 'Content-Type',
}

export async function OPTIONS(): Promise<Response> {
  return new Response(null, { status: 204, headers: CORS_HEADERS })
}

export async function POST(req: Request): Promise<Response> {
  let body: RequestBody
  try {
    body = await req.json()
  } catch {
    return new Response(JSON.stringify({ error: 'Invalid JSON body' }), {
      status: 400,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    })
  }

  const { audio_base64, language, history = [], voice_id, elevenlabs_voice_id, mime_type, level = 'intermediate', native_language = 'en' } = body

  console.log(`[voice-chat] Request received — language: ${language}, has_audio: ${!!audio_base64}, has_voice_id: ${!!voice_id}`)

  if (!language || !LANGUAGE_CONFIG[language]) {
    return new Response(JSON.stringify({ error: `Unsupported language: ${language}` }), {
      status: 400,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    })
  }

  // ── Step 1: Transcribe audio (skip for init call) ──────────────────────────
  const groqKey = process.env.GROQ_API_KEY
  if (!groqKey) {
    return new Response(JSON.stringify({ error: 'GROQ_API_KEY not configured' }), {
      status: 500,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    })
  }

  let user_text = ''

  if (audio_base64) {
    const resolvedMime = mime_type || 'audio/webm'
    const extension = resolvedMime.includes('mp4') ? 'mp4' : 'webm'
    const audioBuffer = Buffer.from(audio_base64, 'base64')
    console.log(`[voice-chat] STT upload: mime=${resolvedMime}, ext=${extension}, size=${audioBuffer.length} bytes`)
    const audioBlob = new Blob([audioBuffer], { type: resolvedMime })

    const formData = new FormData()
    formData.append('file', audioBlob, `audio.${extension}`)
    formData.append('model', 'whisper-large-v3')
    formData.append('response_format', 'json')

    const sttRes = await fetchWithTimeout('https://api.groq.com/openai/v1/audio/transcriptions', {
      method: 'POST',
      headers: { Authorization: `Bearer ${groqKey}` },
      body: formData,
    }, 15000, 'Groq STT')

    if (!sttRes.ok) {
      const errText = await sttRes.text()
      return new Response(JSON.stringify({ error: `Groq STT failed: ${errText}` }), {
        status: 502,
        headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
      })
    }

    const sttJson = await sttRes.json() as { text: string }
    user_text = sttJson.text?.trim() ?? ''
  }

  // ── Step 2: Build LLM messages ─────────────────────────────────────────────
  const systemPrompt = buildSystemPrompt(language, level, native_language)
  const lang = LANGUAGE_CONFIG[language]

  const cleanHistory = history.slice(-20).map(({ role, content }) => ({ role, content }))
  const messages: Message[] = [
    { role: 'system', content: systemPrompt },
    ...cleanHistory,
  ]

  if (user_text) {
    // Normal turn: student said something
    messages.push({ role: 'user', content: user_text })
  } else if (audio_base64) {
    // Audio was provided but STT returned nothing — ask to repeat, don't restart
    const retryResponses: Record<string, string> = {
      en: "I didn't quite catch that — could you try again?",
      de: 'Das habe ich nicht ganz verstanden — kannst du es nochmal versuchen?',
      fr: "Je n'ai pas bien compris — tu peux réessayer ?",
      it: 'Non ho capito bene — puoi riprovare?',
      es: 'No te he entendido bien — ¿puedes intentarlo de nuevo?',
      pt: 'Não entendi bem — pode tentar de novo?',
      nl: 'Ik heb je niet goed verstaan — kun je het nog eens proberen?',
      hi: 'मैं समझ नहीं पाया — क्या आप फिर से कोशिश कर सकते हैं?',
      ar: 'لم أفهم ذلك — هل يمكنك المحاولة مرة أخرى؟',
      fil: 'Hindi ko narinig — puwede mo bang ulitin?',
      id: 'Saya tidak mendengar dengan jelas — bisa coba lagi?',
      ko: '잘 못 들었어요 — 다시 한번 말해 주시겠어요?',
    }
    const retryText = retryResponses[language] ?? retryResponses.en

    const mistralKeyRetry = process.env.MISTRAL_API_KEY
    if (!mistralKeyRetry) {
      return new Response(JSON.stringify({ error: 'MISTRAL_API_KEY not configured' }), {
        status: 500,
        headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
      })
    }
    const retryAudio = await generateSpeech(retryText, language, mistralKeyRetry, voice_id, elevenlabs_voice_id)
    const retryBase64 = retryAudio.toString('base64')

    return new Response(
      JSON.stringify({ user_text: '', ai_text: retryText, audio_base64: retryBase64, audio_format: 'mp3' }),
      { status: 200, headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' } },
    )
  } else {
    // No audio, no text — initial greeting request
    const nativeLangName = LANGUAGE_CONFIG[native_language]?.name || NATIVE_LANGUAGE_NAMES[native_language] || 'English'
    const greetingInstruction = level === 'zero'
      ? `[SYSTEM: The student just joined to learn ${lang.name}. They know ZERO words. Greet them warmly in ${nativeLangName}, tell them you're excited to teach them their first words in ${lang.name}, and teach them how to say "hello" in ${lang.name}. Keep it to 2-3 sentences.]`
      : level === 'beginner'
      ? `[SYSTEM: The student just joined to practice ${lang.name}. They know basic words. Greet them with a simple sentence in ${lang.name}, then add a friendly line in ${nativeLangName}. Ask a simple question they can answer with basic vocabulary.]`
      : `[SYSTEM: The student just joined to practice ${lang.name}. Greet them warmly in ${lang.name} and ask a simple opening question to start the conversation. Keep it to 1-2 sentences.]`
    messages.push({ role: 'user', content: greetingInstruction })
  }

  // ── Step 3: LLM response (Groq, OpenAI-compatible, ~750 tok/s on LPU) ───────
  const llmRes = await fetchWithTimeout('https://api.groq.com/openai/v1/chat/completions', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${groqKey}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      model: 'llama-3.3-70b-versatile',
      messages,
      max_tokens: 200,
    }),
  }, 20000, 'Groq LLM')

  if (!llmRes.ok) {
    const errText = await llmRes.text()
    return new Response(JSON.stringify({ error: `Groq LLM failed: ${errText}` }), {
      status: 502,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    })
  }

  const llmJson = await llmRes.json() as { choices: Array<{ message: { content: string } }> }
  const ai_text = llmJson.choices?.[0]?.message?.content?.trim() ?? ''

  if (!ai_text) {
    return new Response(JSON.stringify({ error: 'LLM returned empty response' }), {
      status: 502,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    })
  }

  // ── Step 4: Text-to-Speech ─────────────────────────────────────────────────
  const mistralKey = process.env.MISTRAL_API_KEY
  if (!mistralKey) {
    return new Response(JSON.stringify({ error: 'MISTRAL_API_KEY not configured' }), {
      status: 500,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    })
  }

  const ttsText = sanitizeForTTS(ai_text)
  let audioBuffer: Buffer
  try {
    audioBuffer = await generateSpeech(ttsText, language, mistralKey, voice_id, elevenlabs_voice_id)
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err)
    return new Response(JSON.stringify({ error: `TTS failed: ${msg}` }), {
      status: 502,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    })
  }
  const audio_base64_out = audioBuffer.toString('base64')

  // ── Step 5: Return response ────────────────────────────────────────────────
  return new Response(
    JSON.stringify({
      user_text,
      ai_text,
      audio_base64: audio_base64_out,
      audio_format: 'mp3',
    }),
    {
      status: 200,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    },
  )
}
