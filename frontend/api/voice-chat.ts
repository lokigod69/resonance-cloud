/**
 * Clean LLM output for TTS consumption.
 * Removes stage directions, pacing dots, and other artifacts
 * that TTS engines would read literally.
 */
function sanitizeForTTS(text: string): string {
  return text
    // Remove parenthetical stage directions: (slowly), (laughing), (whispering), etc.
    .replace(/\([\w\s]+\)/gi, '')
    // Remove bracketed stage directions: [slowly], [pause], etc.
    .replace(/\[[\w\s]+\]/gi, '')
    // Remove pacing ellipsis: "I... am..." → "I am"
    .replace(/\.{2,}/g, ' ')
    // Remove asterisk emphasis: *slowly*, **pause**, etc.
    .replace(/\*+[\w\s]+\*+/g, '')
    // Collapse multiple spaces left by removals
    .replace(/\s{2,}/g, ' ')
    .trim()
}

interface TtsResult {
  audio: Buffer
  format: 'mp3' | 'wav'
}

interface GeminiSpeechOptions {
  characterModeId: string
  voiceName: string
  accentId?: string
}

function buildGeminiTtsPrompt(
  text: string,
  language: string,
  modePrompt: string,
  accentSuffix: string,
): string {
  const lang = LANGUAGE_CONFIG[language]
  const languageLabel = lang ? `${lang.name} (${language})` : language

  return [
    '# PERFORMANCE DIRECTIONS',
    modePrompt,
    accentSuffix ? `\n${accentSuffix}` : '',
    '',
    '# OUTPUT RULES',
    'Read only the transcript inside the <transcript> tags.',
    'Read the transcript exactly as written.',
    `The transcript language is ${languageLabel}. Keep every word in that language.`,
    'Do not translate, paraphrase, summarize, answer, or add commentary.',
    'Do not substitute English words or words from any other language.',
    'If accent or style directions conflict with the transcript language, preserve the transcript language and treat the accent only as a light delivery color.',
    '',
    '<transcript>',
    text,
    '</transcript>',
  ].filter(Boolean).join('\n')
}

async function generateSpeech(
  text: string,
  language: string,
  mistralKey: string,
  voiceId?: string,
  geminiOptions?: GeminiSpeechOptions,
): Promise<TtsResult> {
  // ── Gemini branch — modular character-mode + prebuilt voice ───────────────
  if (geminiOptions) {
    const audio = await generateGeminiSpeech(text, language, geminiOptions)
    return { audio, format: 'wav' }
  }

  if (VOXTRAL_SUPPORTED.has(language)) {
    const voiceConfig = VOICE_MAP[language]
    const ttsBody: Record<string, unknown> = {
      model: 'voxtral-mini-tts-2603',
      input: text,
      response_format: 'mp3',
    }
    const resolvedVoiceId = voiceId || (voiceConfig?.voiceId !== 'xxx' ? voiceConfig?.voiceId : undefined)
    if (resolvedVoiceId) {
      ttsBody.voice_id = resolvedVoiceId
    } else {
      ttsBody.voice = language === 'ar' ? 'en_paul_confident' : 'en_paul_cheerful'
    }
    let ttsResponse: Response | null = null
    for (let attempt = 0; attempt < 2; attempt++) {
      ttsResponse = await fetchWithTimeout('https://api.mistral.ai/v1/audio/speech', {
        method: 'POST',
        headers: {
          Authorization: `Bearer ${mistralKey}`,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify(ttsBody),
      }, 20000, 'Mistral TTS')
      if (ttsResponse.ok) break
      if (attempt === 0) {
        console.warn(`Mistral TTS attempt 1 failed with ${ttsResponse.status}, retrying...`)
        await new Promise(r => setTimeout(r, 500))
      }
    }
    if (!ttsResponse || !ttsResponse.ok) {
      throw new Error(`Mistral TTS failed: ${ttsResponse?.status ?? 'unknown'}`)
    }
    const ttsJson = await ttsResponse.json() as { audio_data?: string }
    if (!ttsJson.audio_data) throw new Error('Mistral TTS returned no audio_data field')
    return { audio: Buffer.from(ttsJson.audio_data, 'base64'), format: 'mp3' }
  } else {
    // Non-Voxtral language (fil, id, ko, ceb) with no explicit Gemini pick —
    // serve it with Gemini TTS using a sensible default mode + voice.
    const audio = await generateGeminiSpeech(text, language, DEFAULT_GEMINI_OPTIONS)
    return { audio, format: 'wav' }
  }
}

/** Generate TTS via Gemini. Combines mode prompt + text in the single-prompt
 *  form documented by Google. Returns a ready-to-play WAV buffer. */
async function generateGeminiSpeech(
  text: string,
  language: string,
  options: GeminiSpeechOptions,
): Promise<Buffer> {
  const mode = getGeminiMode(options.characterModeId)
  if (!mode) throw new Error(`Unknown Gemini character mode: ${options.characterModeId}`)
  if (!GEMINI_VOICE_NAMES.has(options.voiceName)) {
    throw new Error(`Unknown Gemini voice: ${options.voiceName}`)
  }

  const accentId = options.accentId ?? 'none'
  const accentSuffix = GEMINI_ACCENT_SUFFIXES[accentId] ?? ''
  const fullPrompt = buildGeminiTtsPrompt(text, language, mode.geminiStylePrompt, accentSuffix)
  const result = await generateGeminiTtsFromPrompt(fullPrompt, options.voiceName)
  return result.audio
}

function fetchWithTimeout(url: string, options: RequestInit, timeoutMs: number, label: string): Promise<Response> {
  const controller = new AbortController()
  const timer = setTimeout(() => controller.abort(), timeoutMs)
  console.log(`[voice-chat] ${label} — starting (${timeoutMs}ms timeout)`)
  return fetch(url, { ...options, signal: controller.signal })
    .then((res) => {
      clearTimeout(timer)
      console.log(`[voice-chat] ${label} — completed (status ${res.status})`)
      return res
    })
    .catch((err) => {
      clearTimeout(timer)
      if (err.name === 'AbortError') {
        console.error(`[voice-chat] ${label} — TIMED OUT after ${timeoutMs}ms`)
        throw new Error(`${label} timed out after ${timeoutMs / 1000}s`)
      }
      console.error(`[voice-chat] ${label} — FAILED:`, err.message)
      throw err
    })
}

function isObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function readString(value: unknown, field: string, maxLength: number, required = false): string | undefined {
  if (value === undefined || value === null) {
    if (required) throw new ApiError(400, `${field} is required`)
    return undefined
  }
  if (typeof value !== 'string') throw new ApiError(400, `${field} must be a string`)
  const trimmed = value.trim()
  if (required && !trimmed) throw new ApiError(400, `${field} is required`)
  if (trimmed.length > maxLength) throw new ApiError(400, `${field} is too long`)
  return trimmed
}

function validateLanguageKey(value: unknown, field: string, allowNativeNames = false): string {
  const language = readString(value, field, 32, true)!
  if (!LANGUAGE_CONFIG[language] && !(allowNativeNames && NATIVE_LANGUAGE_NAMES[language])) {
    throw new ApiError(400, `Unsupported ${field}`)
  }
  return language
}

function decodedBase64Length(value: string): number {
  if (!/^[A-Za-z0-9+/]*={0,2}$/.test(value) || value.length % 4 !== 0) {
    throw new ApiError(400, 'audio_base64 is malformed')
  }
  const padding = value.endsWith('==') ? 2 : value.endsWith('=') ? 1 : 0
  return (value.length / 4) * 3 - padding
}

function validateMessages(value: unknown, field: string, maxEntries: number): Message[] {
  if (value === undefined || value === null) return []
  if (!Array.isArray(value)) throw new ApiError(400, `${field} must be an array`)
  if (value.length > maxEntries) throw new ApiError(413, `${field} is too large`)
  return value.map((entry, index) => {
    if (!isObject(entry)) throw new ApiError(400, `${field}[${index}] is invalid`)
    const role = entry.role
    if (role !== 'user' && role !== 'assistant' && role !== 'system') {
      throw new ApiError(400, `${field}[${index}].role is invalid`)
    }
    const content = readString(entry.content, `${field}[${index}].content`, MAX_MESSAGE_LENGTH, true)!
    return { role, content }
  })
}

function validateStudyWords(value: unknown): Array<{ word: string; translation: string }> | undefined {
  if (value === undefined || value === null) return undefined
  if (!Array.isArray(value)) throw new ApiError(400, 'study_words must be an array')
  if (value.length > MAX_STUDY_WORDS) throw new ApiError(400, 'study_words has too many entries')
  return value.map((entry, index) => {
    if (!isObject(entry)) throw new ApiError(400, `study_words[${index}] is invalid`)
    return {
      word: readString(entry.word, `study_words[${index}].word`, MAX_STUDY_WORD_FIELD_LENGTH, true)!,
      translation: readString(entry.translation, `study_words[${index}].translation`, MAX_STUDY_WORD_FIELD_LENGTH, true)!,
    }
  })
}

function validateVoiceBody(raw: unknown): RequestBody & {
  transcript?: Array<{ role: string; content: string }>
  message?: string
} {
  if (!isObject(raw)) throw new ApiError(400, 'Request body must be an object')

  const mode = raw.mode
  if (mode !== undefined && mode !== 'corrections' && mode !== 'roleplay') {
    throw new ApiError(400, 'mode is invalid')
  }

  const provider = raw.provider
  if (provider !== undefined && provider !== 'voxtral' && provider !== 'gemini') {
    throw new ApiError(400, 'provider is invalid')
  }

  const language = validateLanguageKey(raw.language, 'language')
  const nativeLanguage = raw.native_language === undefined
    ? undefined
    : validateLanguageKey(raw.native_language, 'native_language', true)

  const audioValue = raw.audio_base64
  let audioBase64: string | null = null
  if (audioValue !== undefined && audioValue !== null) {
    audioBase64 = readString(audioValue, 'audio_base64', MAX_AUDIO_BASE64_LENGTH, false) ?? null
    if (audioBase64) {
      const decodedLength = decodedBase64Length(audioBase64)
      if (decodedLength > MAX_DECODED_AUDIO_BYTES) {
        throw new ApiError(413, 'audio_base64 is too large')
      }
    }
  }

  const transcript = raw.transcript === undefined
    ? undefined
    : validateMessages(raw.transcript, 'transcript', MAX_TRANSCRIPT_ENTRIES)
  if (mode === 'corrections' && transcript && transcript.length < 4) {
    throw new ApiError(400, 'Not enough conversation to review')
  }

  const characterTier = raw.character_tier
  if (characterTier !== undefined && characterTier !== 'style' && characterTier !== 'persona' && characterTier !== 'public') {
    throw new ApiError(400, 'character_tier is invalid')
  }

  return {
    audio_base64: audioBase64,
    language,
    history: validateMessages(raw.history, 'history', MAX_HISTORY_ENTRIES),
    voice_id: readString(raw.voice_id, 'voice_id', 128),
    mime_type: readString(raw.mime_type, 'mime_type', 128),
    level: readString(raw.level, 'level', 64),
    native_language: nativeLanguage,
    character_name: readString(raw.character_name, 'character_name', MAX_CHARACTER_NAME_LENGTH),
    character_tier: characterTier as RequestBody['character_tier'],
    character_identity: readString(raw.character_identity, 'character_identity', MAX_CHARACTER_FIELD_LENGTH),
    character_directive: readString(raw.character_directive, 'character_directive', MAX_CHARACTER_FIELD_LENGTH),
    study_words: validateStudyWords(raw.study_words),
    mode: mode as RequestBody['mode'],
    scenarioPrompt: readString(raw.scenarioPrompt, 'scenarioPrompt', MAX_SCENARIO_PROMPT_LENGTH),
    provider: provider as RequestBody['provider'],
    gemini_character_mode_id: readString(raw.gemini_character_mode_id, 'gemini_character_mode_id', 128),
    gemini_voice_name: readString(raw.gemini_voice_name, 'gemini_voice_name', 128),
    gemini_accent_id: readString(raw.gemini_accent_id, 'gemini_accent_id', 128),
    gemini_vibe_directive: readString(raw.gemini_vibe_directive, 'gemini_vibe_directive', MAX_CHARACTER_FIELD_LENGTH),
    transcript,
    message: readString(raw.message, 'message', MAX_MESSAGE_LENGTH),
  }
}

