async function handleCorrections(body: {
  transcript?: Array<{ role: string; content: string }>
  language?: string
  native_language?: string
}): Promise<Response> {
  const groqKey = process.env.GROQ_API_KEY
  if (!groqKey) {
    return new Response(JSON.stringify({ error: 'GROQ_API_KEY not configured' }), {
      status: 500,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    })
  }

  const transcript = body.transcript || []
  const language = body.language || 'en'
  const native_language = body.native_language || 'en'

  if (transcript.length < 4) {
    return new Response(JSON.stringify({ error: 'Not enough conversation to review' }), {
      status: 400,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    })
  }

  const userMessages = transcript.filter((m) => m.role === 'user')
  if (userMessages.length === 0) {
    return new Response(JSON.stringify({ error: 'No user messages to review' }), {
      status: 400,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    })
  }

  const langName = LANGUAGE_CONFIG[language]?.name || language
  const nativeName = LANGUAGE_CONFIG[native_language]?.name || NATIVE_LANGUAGE_NAMES[native_language] || 'English'

  const systemPrompt = `You are a language teacher reviewing a student's ${langName} conversation practice. The student's native language is ${nativeName}.

Analyze ONLY the student's messages (role: "user") for errors in:
- Grammar
- Word choice / vocabulary
- Sentence structure
- Common expressions (if they used an unnatural phrasing)

For each error found, provide:
- "original": what the student said (exact quote)
- "corrected": the correct version
- "explanation": brief explanation in ${nativeName} of what was wrong and why the correction is better

If the student made no significant errors, return an empty array.
Be encouraging but honest. Focus on errors that would matter in real conversation — ignore minor stylistic preferences.

Respond with a JSON object of the form {"corrections": [{"original": "...", "corrected": "...", "explanation": "..."}]}.
If no errors: {"corrections": []}`

  try {
    const llmRes = await fetchWithTimeout('https://api.groq.com/openai/v1/chat/completions', {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${groqKey}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        model: 'llama-3.3-70b-versatile',
        messages: [
          { role: 'system', content: systemPrompt },
          { role: 'user', content: JSON.stringify(transcript) },
        ],
        response_format: { type: 'json_object' },
      }),
    }, 30000, 'Groq Corrections')

    if (!llmRes.ok) {
      const errText = await llmRes.text()
      return new Response(JSON.stringify({ error: `Groq LLM failed: ${errText}` }), {
        status: 502,
        headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
      })
    }

    const llmJson = await llmRes.json() as { choices: Array<{ message: { content: string } }> }
    const text = llmJson.choices?.[0]?.message?.content?.trim() || '[]'

    let corrections: unknown
    try {
      corrections = JSON.parse(text)
    } catch {
      corrections = []
    }
    if (!Array.isArray(corrections)) {
      const obj = corrections as Record<string, unknown>
      corrections = obj.corrections || obj.errors || []
    }
    if (!Array.isArray(corrections)) corrections = []

    return new Response(JSON.stringify({ corrections }), {
      status: 200,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    })
  } catch (err) {
    return new Response(JSON.stringify({ error: err instanceof Error ? err.message : 'Corrections failed' }), {
      status: 502,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    })
  }
}

export async function POST(req: Request): Promise<Response> {
  let body: RequestBody & { mode?: string; transcript?: Array<{ role: string; content: string }>; message?: string }
  try {
    body = await req.json()
  } catch {
    return new Response(JSON.stringify({ error: 'Invalid JSON body' }), {
      status: 400,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    })
  }

  if (body.mode === 'corrections') {
    return handleCorrections(body)
  }

  const { audio_base64, language, history = [], voice_id, elevenlabs_voice_id, mime_type, level = 'intermediate', native_language = 'en', character_name, character_tier, character_identity, character_directive, study_words, scenarioPrompt } = body
  const isRoleplay = body.mode === 'roleplay' && !!scenarioPrompt
  const roleplayText = typeof body.message === 'string' ? body.message : null

  const character: CharacterPayload | undefined = character_name && character_tier && character_directive
    ? { name: character_name, tier: character_tier, identity: character_identity, directive: character_directive }
    : undefined

  console.log(`[voice-chat] Request received — language: ${language}, has_audio: ${!!audio_base64}, has_voice_id: ${!!voice_id}`)

  if (!language || !LANGUAGE_CONFIG[language]) {
    return new Response(JSON.stringify({ error: `Unsupported language: ${language}` }), {
      status: 400,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    })
  }

  // ── Step 1: Transcribe audio (skip for init call) ──────────────────────────
  const groqKey = process.env.GROQ_API_KEY
  if (!groqKey) {
    return new Response(JSON.stringify({ error: 'GROQ_API_KEY not configured' }), {
      status: 500,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    })
  }

  let user_text = ''

  // Roleplay text path: client may send text (including the __ROLEPLAY_OPEN__ sentinel)
  // instead of audio. Skip STT entirely in that case. Always self-contained:
  // if message is absent, default to the scene-open instruction so the roleplay
  // branch never falls through to the freeform greeting path.
  if (isRoleplay && !audio_base64) {
    if (!roleplayText || roleplayText === '__ROLEPLAY_OPEN__') {
      user_text = '[Begin the scene. Deliver your opening line now. Do not wait for the user.]'
    } else {
      user_text = roleplayText
    }
  } else if (audio_base64) {
    const resolvedMime = mime_type || 'audio/webm'
    const extension = resolvedMime.includes('mp4') ? 'mp4' : 'webm'
    const audioBuffer = Buffer.from(audio_base64, 'base64')
    console.log(`[voice-chat] STT upload: mime=${resolvedMime}, ext=${extension}, size=${audioBuffer.length} bytes`)
    const audioBlob = new Blob([audioBuffer], { type: resolvedMime })

    const formData = new FormData()
    formData.append('file', audioBlob, `audio.${extension}`)
    formData.append('model', 'whisper-large-v3')
    formData.append('response_format', 'json')

    const sttRes = await fetchWithTimeout('https://api.groq.com/openai/v1/audio/transcriptions', {
      method: 'POST',
      headers: { Authorization: `Bearer ${groqKey}` },
      body: formData,
    }, 15000, 'Groq STT')

    if (!sttRes.ok) {
      const errText = await sttRes.text()
      return new Response(JSON.stringify({ error: `Groq STT failed: ${errText}` }), {
        status: 502,
        headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
      })
    }

    const sttJson = await sttRes.json() as { text: string }
    user_text = sttJson.text?.trim() ?? ''
  }

  // ── Step 2: Build LLM messages ─────────────────────────────────────────────
  const systemPrompt = buildSystemPrompt(language, level, native_language, character, study_words, isRoleplay ? scenarioPrompt : undefined)
  const lang = LANGUAGE_CONFIG[language]

  const cleanHistory = history.slice(-20).map(({ role, content }) => ({ role, content }))
  const messages: Message[] = [
    { role: 'system', content: systemPrompt },
    ...cleanHistory,
  ]

  if (user_text) {
    // Normal turn: student said something
    messages.push({ role: 'user', content: user_text })
  } else if (audio_base64) {
    // Audio was provided but STT returned nothing — ask to repeat, don't restart
    const retryResponses: Record<string, string> = {
      en: "I didn't quite catch that — could you try again?",
      de: 'Das habe ich nicht ganz verstanden — kannst du es nochmal versuchen?',
      fr: "Je n'ai pas bien compris — tu peux réessayer ?",
      it: 'Non ho capito bene — puoi riprovare?',
      es: 'No te he entendido bien — ¿puedes intentarlo de nuevo?',
      pt: 'Não entendi bem — pode tentar de novo?',
      nl: 'Ik heb je niet goed verstaan — kun je het nog eens proberen?',
      hi: 'मैं समझ नहीं पाया — क्या आप फिर से कोशिश कर सकते हैं?',
      ar: 'لم أفهم ذلك — هل يمكنك المحاولة مرة أخرى؟',
      fil: 'Hindi ko narinig — puwede mo bang ulitin?',
      id: 'Saya tidak mendengar dengan jelas — bisa coba lagi?',
      ko: '잘 못 들었어요 — 다시 한번 말해 주시겠어요?',
    }
    const retryText = retryResponses[language] ?? retryResponses.en

    const mistralKeyRetry = process.env.MISTRAL_API_KEY
    if (!mistralKeyRetry) {
      return new Response(JSON.stringify({ error: 'MISTRAL_API_KEY not configured' }), {
        status: 500,
        headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
      })
    }
    const retryAudio = await generateSpeech(retryText, language, mistralKeyRetry, voice_id, elevenlabs_voice_id)
    const retryBase64 = retryAudio.toString('base64')

    return new Response(
      JSON.stringify({ user_text: '', ai_text: retryText, audio_base64: retryBase64, audio_format: 'mp3' }),
      { status: 200, headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' } },
    )
  } else {
    // No audio, no text — initial greeting request
    const nativeLangName = LANGUAGE_CONFIG[native_language]?.name || NATIVE_LANGUAGE_NAMES[native_language] || 'English'
    const charIntro = character
      ? ` IN CHARACTER as ${character.name}. Introduce yourself briefly (one sentence about who you are), then`
      : ''
    const hasStudyWords = study_words && study_words.length > 0
    let greetingInstruction: string
    if (level === 'zero') {
      if (hasStudyWords) {
        const w = study_words![Math.floor(Math.random() * study_words!.length)]
        greetingInstruction = `[SYSTEM: New conversation. Greet them warmly in ${nativeLangName}.${charIntro ? charIntro : ''} Introduce the ${lang.name} word "${w.word}" (meaning: "${w.translation}") naturally — weave it into a question or a fun fact rather than presenting it as a vocabulary item. Keep it to 2-3 sentences. Stay in character.]`
      } else {
        greetingInstruction = `[SYSTEM: New conversation. Greet them warmly in ${nativeLangName}.${charIntro ? charIntro : ''} Start with something human — ask how they're doing, what brought them here, or share something interesting about ${lang.name} culture. Introduce one ${lang.name} word that fits the moment naturally. Keep it to 2-3 sentences. Stay in character.]`
      }
    } else if (level === 'beginner') {
      greetingInstruction = `[SYSTEM: This is the start of a new conversation. Greet them with a simple sentence in ${lang.name}${charIntro ? charIntro : ''}, and follow up in ${nativeLangName} if needed. Ask a simple opening question. VARY your opener — do not always start the same way. Keep it to 2-3 sentences. Stay in character.]`
    } else {
      greetingInstruction = `[SYSTEM: This is the start of a new conversation.${charIntro ? charIntro : ''} Greet them warmly in ${lang.name} and ask a simple opening question. VARY your opener — sometimes ask about their day, sometimes share something interesting, sometimes pose a fun question. Keep it to 1-2 sentences. Stay in character.]`
    }
    messages.push({ role: 'user', content: greetingInstruction })
  }

  // ── Step 3: LLM response (Groq, OpenAI-compatible, ~750 tok/s on LPU) ───────
  const llmRes = await fetchWithTimeout('https://api.groq.com/openai/v1/chat/completions', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${groqKey}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      model: 'llama-3.3-70b-versatile',
      messages,
      max_tokens: 200,
    }),
  }, 20000, 'Groq LLM')

  if (!llmRes.ok) {
    const errText = await llmRes.text()
    return new Response(JSON.stringify({ error: `Groq LLM failed: ${errText}` }), {
      status: 502,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    })
  }

  const llmJson = await llmRes.json() as { choices: Array<{ message: { content: string } }> }
  const ai_text = llmJson.choices?.[0]?.message?.content?.trim() ?? ''

  if (!ai_text) {
    return new Response(JSON.stringify({ error: 'LLM returned empty response' }), {
      status: 502,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    })
  }

  // ── Step 4: Text-to-Speech ─────────────────────────────────────────────────
  const mistralKey = process.env.MISTRAL_API_KEY
  if (!mistralKey) {
    return new Response(JSON.stringify({ error: 'MISTRAL_API_KEY not configured' }), {
      status: 500,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    })
  }

  const ttsText = sanitizeForTTS(ai_text)
  let audio_base64_out = ''
  const audio_format = 'mp3'

  try {
    const audioBuffer = await generateSpeech(ttsText, language, mistralKey, voice_id, elevenlabs_voice_id)
    audio_base64_out = audioBuffer.toString('base64')
  } catch (ttsErr) {
    // TTS failed — log it but don't fail the whole request
    console.warn('[voice-chat] TTS failed, returning text-only response:', ttsErr instanceof Error ? ttsErr.message : ttsErr)
    // audio_base64_out stays empty — client will show text without audio
  }

  // ── Step 5: Return response ────────────────────────────────────────────────
  return new Response(
    JSON.stringify({
      user_text,
      ai_text,
      audio_base64: audio_base64_out,
      audio_format,
    }),
    {
      status: 200,
      headers: { ...CORS_HEADERS, 'Content-Type': 'application/json' },
    },
  )
}
