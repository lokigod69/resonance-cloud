/**
 * German A2 — the Regular tier (10 paths × 10 lessons), per
 * docs/Product/FABLE_A2_LEARNING_PATH_DESIGN.md (§4 integration, §5 authoring
 * contract) and the phase-3 spec in tmp\A2_GERMAN_P1_P10_SPEC.md.
 *
 * Authoring contract highlights enforced in this module:
 * - Base language is ENGLISH (matching German A1): all GuidedBaseContentText
 *   fields carry .en only; lesson.situation additionally carries the required
 *   .de rendering (du-form German, as in A1).
 * - Two-turn shape: sceneCaption carries the interlocutor's German line quoted
 *   inside the .en caption; the learner's corePhrase is the response.
 * - Register locked per path and documented in the spec: Sie for service paths
 *   (P1–P3, P5–P7, P9), du for the friend/neighbor paths (P4, P8, P10) —
 *   matching German A1's split (Sie at counters, du in social paths). No
 *   mid-path switches.
 * - Tense contract: present everywhere; Perfekt only from the whitelist
 *   (P3/P9 + light recycling); war/hatte are the only Präteritum forms allowed.
 *   German participles never agree with the speaker, so both haben- and
 *   sein-Perfekt are safe. Future = present + time expression (no werden).
 *   weil sends the verb to the end — checked at review, every time.
 * - Locale hygiene: real umlauts (ä/ö/ü) and ß everywhere, never digraphs;
 *   quoted interlocutor German inside captions is the only German in .en fields.
 * - Trophies unique across the entire German guided corpus (A1 + A2); German
 *   nouns keep their capital letter.
 */
