/** Rebuild the Script Lab manifest from local MP3s only; never calls a provider. */
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import type { ScriptAudioSpec } from '../src/lib/scriptlab/types.ts'
import { localAudioSpecs } from './script-lab-local-inventory.ts'
import { SCRIPTS } from '../src/lib/scriptlab/registry.ts'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

function checkImportedSymbols(
  dir: string,
  expectedIds: string[],
  files: string[],
): void {
  const credits = fs.readFileSync(path.join(dir, 'credits.html'), 'utf8')
  const { recordings } = JSON.parse(fs.readFileSync(path.join(dir, 'provenance.json'), 'utf8')) as {
    recordings: { itemId: string; author: string; licenseUrl: string; sourcePage: string; outputSha256: string }[]
  }
  if (recordings.length !== expectedIds.length || files.length !== expectedIds.length) {
    throw new Error(`Incomplete alphabet recordings: ${dir}`)
  }
  const byId = new Map(recordings.map((record) => [record.itemId, record]))
  for (const itemId of expectedIds) {
    const record = byId.get(itemId)
    if (!record || !record.author || !record.licenseUrl || !record.sourcePage || !credits.includes(record.author) || !credits.includes(record.sourcePage) || !credits.includes(record.licenseUrl)) {
      throw new Error(`Missing audio credit for ${itemId} in ${dir}`)
    }
    const bytes = fs.readFileSync(path.join(dir, `${itemId}.mp3`))
    if (createHash('sha256').update(bytes).digest('hex') !== record.outputSha256) {
      throw new Error(`Recording checksum mismatch: ${itemId}`)
    }
  }
}

function checkLocalRecordings(scriptId: string, language: string, dir: string, specs: ScriptAudioSpec[]) {
  const receipt = JSON.parse(fs.readFileSync(path.join(dir, 'provenance.json'), 'utf8')) as {
    scriptId: string
    engine: string
    modelRevision: string
    model: string
    language: string
    voice: string
    schemaVersion: number
    processingVersion: number
    recordings: { itemId: string; text: string; file: string; outputSha256: string }[]
  }
  if (receipt.engine !== 'supertonic' || receipt.model !== 'supertonic-3' || receipt.voice !== 'F1'
    || receipt.schemaVersion !== 1 || receipt.processingVersion !== 2 || receipt.language !== language
    || receipt.modelRevision !== '3cadd1ee6394adea1bd021217a0e650ede09a323') {
    throw new Error(`Unrecognized pronunciation model for ${scriptId}`)
  }
  const byId = new Map(receipt.recordings.map((record) => [record.itemId, record]))
  const files = fs.readdirSync(dir).filter((file) => file.endsWith('.mp3'))
  if (receipt.scriptId !== scriptId || files.length !== specs.length || receipt.recordings.length !== specs.length) {
    throw new Error(`Incomplete local pronunciation pack: ${scriptId}`)
  }
  for (const { itemId, text } of specs) {
    const record = byId.get(itemId)
    if (!record || record.text !== text || record.file !== `${itemId}.mp3`) throw new Error(`Wrong recording for ${itemId}`)
    const hash = createHash('sha256').update(fs.readFileSync(path.join(dir, record.file))).digest('hex')
    if (hash !== record.outputSha256) throw new Error(`Invalid local pronunciation checksum: ${itemId}`)
  }
}

export async function rebuildScriptAudioManifest(checkOnly = false): Promise<void> {
  let hangulBlocks = ''
  const manifest: Record<string, Record<string, string>> = {}
  for (const { id, load } of SCRIPTS) {
    const dir = path.join(root, 'public/scripts', id)
    const entries: Record<string, string> = {}
    const files = fs.readdirSync(dir).filter((name) => name.endsWith('.mp3')).sort()
    const { default: script } = await load()
    if (id === 'russian-cyrillic' || id === 'japanese-hiragana') {
      checkImportedSymbols(dir, script.symbols.map((symbol) => symbol.audio.itemId), files)
    }
    for (const file of files) {
      const itemId = file.slice(0, -4)
      if (!/^[a-z0-9-]+$/.test(itemId)) throw new Error(`Invalid Script Lab audio filename: ${file}`)
      entries[itemId] = `/scripts/${id}/${file}`
    }
    const local = localAudioSpecs(script)
    if (local.length) {
      checkLocalRecordings(id, script.speechLang.split('-')[0], path.join(dir, 'local-tts'), local)
      if (id === 'korean-hangul') {
        // The 3,000+ Unicode blocks need just one character each in the browser.
        hangulBlocks = local.map((spec) => spec.text).sort().join('')
      } else {
        for (const { itemId } of local) entries[itemId] = `/scripts/${id}/local-tts/${itemId}.mp3`
      }
    }
    if (Object.keys(entries).length) manifest[id] = entries
  }
  const dest = path.join(root, 'src/lib/scriptlab/audioManifest.generated.ts')
  const contents = [
    '// AUTO-GENERATED by scripts/rebuild-script-lab-audio-manifest.ts — do not edit by hand.',
    '// Maps scriptId → audio itemId → static asset path under public/.',
    '',
    `export const GENERATED_SCRIPT_AUDIO: Record<string, Record<string, string>> = ${JSON.stringify(manifest, null, 2)}`,
    '',
    `export const GENERATED_HANGUL_BLOCKS = ${JSON.stringify(hangulBlocks)}`,
    '',
  ].join('\n')
  if (checkOnly) {
    if (fs.readFileSync(dest, 'utf8').replace(/\r\n/g, '\n') !== contents) throw new Error('Rebuild the Script Lab manifest')
    return
  }
  fs.writeFileSync(dest, contents)
  console.log(`Script Lab manifest rebuilt from disk (${Object.keys(manifest).length} scripts).`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await rebuildScriptAudioManifest(process.argv.includes('--check'))
}
